/**
 * useDatasetKnowledge Hook
 * 
 * React hook for accessing dataset knowledge throughout the app.
 * Provides easy access to knowledge base, semantic search, and insights.
 */

import { useState, useEffect, useCallback, useMemo } from 'react';
import { Dataset } from '../types';
import { 
  getDatasetKnowledge, 
  updateDatasetKnowledge, 
  addDatasetStory,
  autoGenerateDataDictionary,
  DatasetKnowledge,
  DatasetStory
} from '../lib/datasetKnowledge';
import { searchKnowledge, indexDatasetKnowledge, SearchResult } from '../lib/embeddingService';

interface UseDatasetKnowledgeReturn {
  // Knowledge state
  knowledge: DatasetKnowledge | null;
  isLoading: boolean;
  error: string | null;
  
  // Knowledge operations
  refresh: () => Promise<void>;
  updateKnowledge: (updates: Partial<DatasetKnowledge>) => Promise<void>;
  addStory: (story: Omit<DatasetStory, 'id' | 'createdAt'>) => Promise<void>;
  
  // Semantic search
  search: (query: string) => Promise<SearchResult[]>;
  
  // Derived data
  hasKnownIssues: boolean;
  knownIssuesCount: number;
  storiesCount: number;
  hasBusinessContext: boolean;
  hasDictionary: boolean;
  insightsCount: number;
  
  // Quick access
  recentInsights: { question: string; answer: string }[];
  recentStories: DatasetStory[];
  columnDescriptions: Record<string, string>;
}

export const useDatasetKnowledge = (dataset: Dataset | null): UseDatasetKnowledgeReturn => {
  const [knowledge, setKnowledge] = useState<DatasetKnowledge | null>(null);
  const [isLoading, setIsLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // Load knowledge when dataset changes
  const loadKnowledge = useCallback(async () => {
    if (!dataset?.id) {
      setKnowledge(null);
      return;
    }

    setIsLoading(true);
    setError(null);

    try {
      const data = await getDatasetKnowledge(dataset.id, dataset.name);
      
      // Auto-generate dictionary if missing
      if (!data.dataDictionary?.columns?.length && dataset.preview_data?.columns?.length) {
        const autoDictionary = autoGenerateDataDictionary(dataset);
        data.dataDictionary = autoDictionary;
        await updateDatasetKnowledge(dataset.id, { 
          datasetName: dataset.name,
          dataDictionary: autoDictionary 
        });
      }
      
      setKnowledge(data);
    } catch (e: any) {
      setError(e.message || 'Failed to load knowledge');
    } finally {
      setIsLoading(false);
    }
  }, [dataset?.id, dataset?.name]);

  useEffect(() => {
    loadKnowledge();
  }, [loadKnowledge]);

  // Update knowledge
  const updateKnowledgeHandler = useCallback(async (updates: Partial<DatasetKnowledge>) => {
    if (!dataset?.id) return;

    try {
      const updated = await updateDatasetKnowledge(dataset.id, updates);
      setKnowledge(prev => prev ? { ...prev, ...updates } : null);
      
      // Re-index for semantic search
      await indexDatasetKnowledge(dataset.id, {
        businessContext: updates.businessContext || knowledge?.businessContext,
        stories: updates.stories || knowledge?.stories,
        dataDictionary: updates.dataDictionary || knowledge?.dataDictionary,
        analysisHistory: updates.analysisHistory || knowledge?.analysisHistory
      });
    } catch (e: any) {
      setError(e.message);
    }
  }, [dataset?.id, knowledge]);

  // Add story
  const addStoryHandler = useCallback(async (story: Omit<DatasetStory, 'id' | 'createdAt'>) => {
    if (!dataset?.id) return;

    try {
      const newStory = await addDatasetStory(dataset.id, story);
      setKnowledge(prev => prev ? {
        ...prev,
        stories: [...prev.stories, newStory]
      } : null);
    } catch (e: any) {
      setError(e.message);
    }
  }, [dataset?.id]);

  // Semantic search
  const searchHandler = useCallback(async (query: string): Promise<SearchResult[]> => {
    if (!dataset?.id) return [];

    try {
      return await searchKnowledge(query, {
        datasetId: dataset.id,
        matchThreshold: 0.6,
        matchCount: 5
      });
    } catch (e) {
      console.error('Search error:', e);
      return [];
    }
  }, [dataset?.id]);

  // Derived values
  const hasKnownIssues = useMemo(() => 
    (knowledge?.knownIssues?.length || 0) > 0, [knowledge?.knownIssues]);
  
  const knownIssuesCount = useMemo(() => 
    knowledge?.knownIssues?.length || 0, [knowledge?.knownIssues]);
  
  const storiesCount = useMemo(() => 
    knowledge?.stories?.length || 0, [knowledge?.stories]);
  
  const hasBusinessContext = useMemo(() => 
    !!knowledge?.businessContext?.trim(), [knowledge?.businessContext]);
  
  const hasDictionary = useMemo(() => 
    (knowledge?.dataDictionary?.columns?.length || 0) > 0, [knowledge?.dataDictionary]);
  
  const insightsCount = useMemo(() => 
    knowledge?.analysisHistory?.length || 0, [knowledge?.analysisHistory]);

  // Recent insights (last 5)
  const recentInsights = useMemo(() => 
    knowledge?.analysisHistory?.slice(-5).reverse() || [], [knowledge?.analysisHistory]);

  // Recent stories (last 5)
  const recentStories = useMemo(() => 
    knowledge?.stories?.slice(-5).reverse() || [], [knowledge?.stories]);

  // Column descriptions map
  const columnDescriptions = useMemo(() => {
    const map: Record<string, string> = {};
    knowledge?.dataDictionary?.columns?.forEach(col => {
      map[col.name] = col.businessMeaning || col.description;
    });
    return map;
  }, [knowledge?.dataDictionary]);

  return {
    knowledge,
    isLoading,
    error,
    refresh: loadKnowledge,
    updateKnowledge: updateKnowledgeHandler,
    addStory: addStoryHandler,
    search: searchHandler,
    hasKnownIssues,
    knownIssuesCount,
    storiesCount,
    hasBusinessContext,
    hasDictionary,
    insightsCount,
    recentInsights,
    recentStories,
    columnDescriptions
  };
};

export default useDatasetKnowledge;

