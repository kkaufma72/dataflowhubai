/**
 * Dataset Knowledge Panel
 * 
 * UI for managing dataset knowledge including:
 * - Data dictionary
 * - Stories and notes
 * - Business context
 * - Domain and tags
 */

import React, { useState, useEffect } from 'react';
import { 
  BookOpen, 
  Plus, 
  Save, 
  FileText, 
  Tag, 
  Building2, 
  RefreshCw,
  MessageSquare,
  AlertTriangle,
  Lightbulb,
  Target,
  HelpCircle,
  StickyNote,
  ChevronDown,
  ChevronUp,
  Trash2,
  Edit2,
  Check,
  X
} from 'lucide-react';
import { Dataset } from '../../types';
import { 
  getDatasetKnowledge, 
  updateDatasetKnowledge, 
  addDatasetStory,
  autoGenerateDataDictionary,
  DatasetKnowledge,
  DatasetStory,
  ColumnDefinition
} from '../../lib/datasetKnowledge';
import { indexDatasetKnowledge } from '../../lib/embeddingService';
import toast from 'react-hot-toast';

interface DatasetKnowledgePanelProps {
  dataset: Dataset;
  onClose?: () => void;
}

const STORY_CATEGORIES = [
  { value: 'context', label: 'Business Context', icon: Building2, color: 'blue' },
  { value: 'insight', label: 'Insight', icon: Lightbulb, color: 'yellow' },
  { value: 'issue', label: 'Known Issue', icon: AlertTriangle, color: 'red' },
  { value: 'goal', label: 'Goal/Objective', icon: Target, color: 'green' },
  { value: 'question', label: 'Open Question', icon: HelpCircle, color: 'purple' },
  { value: 'note', label: 'General Note', icon: StickyNote, color: 'gray' }
];

const DOMAINS = [
  'finance', 'marketing', 'sales', 'operations', 'hr', 
  'healthcare', 'retail', 'ecommerce', 'real-estate', 'economic', 'other'
];

const DatasetKnowledgePanel: React.FC<DatasetKnowledgePanelProps> = ({ dataset, onClose }) => {
  const [knowledge, setKnowledge] = useState<DatasetKnowledge | null>(null);
  const [isLoading, setIsLoading] = useState(true);
  const [activeTab, setActiveTab] = useState<'overview' | 'dictionary' | 'stories' | 'history'>('overview');
  
  // Form states
  const [businessContext, setBusinessContext] = useState('');
  const [dataSource, setDataSource] = useState('');
  const [dataOwner, setDataOwner] = useState('');
  const [refreshFrequency, setRefreshFrequency] = useState('');
  const [domain, setDomain] = useState('');
  const [tags, setTags] = useState<string[]>([]);
  const [newTag, setNewTag] = useState('');
  
  // Story form
  const [showStoryForm, setShowStoryForm] = useState(false);
  const [storyTitle, setStoryTitle] = useState('');
  const [storyContent, setStoryContent] = useState('');
  const [storyCategory, setStoryCategory] = useState<DatasetStory['category']>('note');
  
  // Dictionary editing
  const [editingColumn, setEditingColumn] = useState<string | null>(null);
  const [columnDescription, setColumnDescription] = useState('');
  const [columnBusinessMeaning, setColumnBusinessMeaning] = useState('');
  
  const [expandedSections, setExpandedSections] = useState({
    context: true,
    dictionary: false,
    stories: true,
    history: false
  });

  useEffect(() => {
    loadKnowledge();
  }, [dataset.id]);

  const loadKnowledge = async () => {
    setIsLoading(true);
    try {
      const data = await getDatasetKnowledge(dataset.id, dataset.name);
      setKnowledge(data);
      
      // Populate form fields
      setBusinessContext(data.businessContext || '');
      setDataSource(data.dataSource || '');
      setDataOwner(data.dataOwner || '');
      setRefreshFrequency(data.refreshFrequency || '');
      setDomain(data.domain || '');
      setTags(data.tags || []);
      
      // Auto-generate dictionary if empty
      if (!data.dataDictionary?.columns?.length) {
        const autoDictionary = autoGenerateDataDictionary(dataset);
        await updateDatasetKnowledge(dataset.id, {
          datasetName: dataset.name,
          dataDictionary: autoDictionary
        });
        setKnowledge(prev => prev ? { ...prev, dataDictionary: autoDictionary } : null);
      }
    } catch (error) {
      console.error('Failed to load knowledge:', error);
      toast.error('Failed to load dataset knowledge');
    } finally {
      setIsLoading(false);
    }
  };

  const saveOverview = async () => {
    try {
      await updateDatasetKnowledge(dataset.id, {
        datasetName: dataset.name,
        businessContext,
        dataSource,
        dataOwner,
        refreshFrequency,
        domain,
        tags
      });
      
      // Re-index for semantic search
      if (knowledge) {
        toast.loading('Indexing for semantic search...', { id: 'indexing' });
        await indexDatasetKnowledge(dataset.id, {
          businessContext,
          stories: knowledge.stories,
          dataDictionary: knowledge.dataDictionary,
          analysisHistory: knowledge.analysisHistory
        });
        toast.dismiss('indexing');
      }
      
      toast.success('Knowledge saved & indexed!');
    } catch (error) {
      toast.error('Failed to save');
    }
  };

  const handleAddStory = async () => {
    if (!storyTitle.trim() || !storyContent.trim()) {
      toast.error('Please fill in title and content');
      return;
    }
    
    try {
      const newStory = await addDatasetStory(dataset.id, {
        title: storyTitle,
        content: storyContent,
        category: storyCategory
      });
      
      setKnowledge(prev => prev ? {
        ...prev,
        stories: [...prev.stories, newStory]
      } : null);
      
      setStoryTitle('');
      setStoryContent('');
      setShowStoryForm(false);
      toast.success('Story added!');
    } catch (error) {
      toast.error('Failed to add story');
    }
  };

  const handleAddTag = () => {
    if (newTag.trim() && !tags.includes(newTag.trim())) {
      setTags([...tags, newTag.trim()]);
      setNewTag('');
    }
  };

  const handleRemoveTag = (tag: string) => {
    setTags(tags.filter(t => t !== tag));
  };

  const handleUpdateColumn = async (columnName: string) => {
    if (!knowledge?.dataDictionary) return;
    
    const updatedColumns = knowledge.dataDictionary.columns.map(col => 
      col.name === columnName 
        ? { ...col, description: columnDescription, businessMeaning: columnBusinessMeaning }
        : col
    );
    
    await updateDatasetKnowledge(dataset.id, {
      dataDictionary: { ...knowledge.dataDictionary, columns: updatedColumns }
    });
    
    setKnowledge(prev => prev ? {
      ...prev,
      dataDictionary: { ...prev.dataDictionary!, columns: updatedColumns }
    } : null);
    
    setEditingColumn(null);
    toast.success('Column updated!');
  };

  const toggleSection = (section: keyof typeof expandedSections) => {
    setExpandedSections(prev => ({ ...prev, [section]: !prev[section] }));
  };

  if (isLoading) {
    return (
      <div className="flex items-center justify-center py-12">
        <RefreshCw className="w-8 h-8 animate-spin text-indigo-600" />
      </div>
    );
  }

  const getCategoryIcon = (category: string) => {
    const cat = STORY_CATEGORIES.find(c => c.value === category);
    return cat ? cat.icon : StickyNote;
  };

  const getCategoryColor = (category: string) => {
    const colors: Record<string, string> = {
      context: 'bg-blue-100 text-blue-700',
      insight: 'bg-yellow-100 text-yellow-700',
      issue: 'bg-red-100 text-red-700',
      goal: 'bg-green-100 text-green-700',
      question: 'bg-purple-100 text-purple-700',
      note: 'bg-gray-100 text-gray-700'
    };
    return colors[category] || colors.note;
  };

  return (
    <div className="bg-white rounded-xl shadow-lg overflow-hidden max-h-[80vh] flex flex-col">
      {/* Header */}
      <div className="bg-gradient-to-r from-indigo-600 to-purple-600 px-6 py-4">
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-3">
            <BookOpen className="w-6 h-6 text-white" />
            <div>
              <h2 className="text-lg font-semibold text-white">Dataset Knowledge</h2>
              <p className="text-indigo-200 text-sm">{dataset.name}</p>
            </div>
          </div>
          {onClose && (
            <button onClick={onClose} className="text-white/80 hover:text-white">
              <X className="w-5 h-5" />
            </button>
          )}
        </div>
      </div>

      {/* Tabs */}
      <div className="flex border-b bg-gray-50">
        {[
          { id: 'overview', label: 'Overview', icon: FileText },
          { id: 'dictionary', label: 'Data Dictionary', icon: BookOpen },
          { id: 'stories', label: 'Notes & Stories', icon: MessageSquare },
          { id: 'history', label: 'Analysis History', icon: Lightbulb }
        ].map(tab => (
          <button
            key={tab.id}
            onClick={() => setActiveTab(tab.id as any)}
            className={`flex items-center gap-2 px-4 py-3 text-sm font-medium border-b-2 transition-colors ${
              activeTab === tab.id
                ? 'border-indigo-600 text-indigo-600 bg-white'
                : 'border-transparent text-gray-600 hover:text-gray-900'
            }`}
          >
            <tab.icon className="w-4 h-4" />
            {tab.label}
          </button>
        ))}
      </div>

      {/* Content */}
      <div className="flex-1 overflow-y-auto p-6">
        {/* Overview Tab */}
        {activeTab === 'overview' && (
          <div className="space-y-6">
            {/* Business Context */}
            <div>
              <label className="block text-sm font-medium text-gray-700 mb-2">
                Business Context
              </label>
              <textarea
                value={businessContext}
                onChange={(e) => setBusinessContext(e.target.value)}
                placeholder="What does this data represent? How is it used in business decisions?"
                className="w-full px-4 py-3 border rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500"
                rows={3}
              />
            </div>

            {/* Data Source */}
            <div className="grid grid-cols-2 gap-4">
              <div>
                <label className="block text-sm font-medium text-gray-700 mb-2">
                  Data Source
                </label>
                <input
                  type="text"
                  value={dataSource}
                  onChange={(e) => setDataSource(e.target.value)}
                  placeholder="e.g., Salesforce, Google Analytics, Internal DB"
                  className="w-full px-4 py-2 border rounded-lg focus:ring-2 focus:ring-indigo-500"
                />
              </div>
              <div>
                <label className="block text-sm font-medium text-gray-700 mb-2">
                  Data Owner
                </label>
                <input
                  type="text"
                  value={dataOwner}
                  onChange={(e) => setDataOwner(e.target.value)}
                  placeholder="e.g., Marketing Team, John Smith"
                  className="w-full px-4 py-2 border rounded-lg focus:ring-2 focus:ring-indigo-500"
                />
              </div>
            </div>

            {/* Refresh & Domain */}
            <div className="grid grid-cols-2 gap-4">
              <div>
                <label className="block text-sm font-medium text-gray-700 mb-2">
                  Refresh Frequency
                </label>
                <select
                  value={refreshFrequency}
                  onChange={(e) => setRefreshFrequency(e.target.value)}
                  className="w-full px-4 py-2 border rounded-lg focus:ring-2 focus:ring-indigo-500"
                >
                  <option value="">Select frequency</option>
                  <option value="real-time">Real-time</option>
                  <option value="hourly">Hourly</option>
                  <option value="daily">Daily</option>
                  <option value="weekly">Weekly</option>
                  <option value="monthly">Monthly</option>
                  <option value="quarterly">Quarterly</option>
                  <option value="one-time">One-time upload</option>
                </select>
              </div>
              <div>
                <label className="block text-sm font-medium text-gray-700 mb-2">
                  Domain
                </label>
                <select
                  value={domain}
                  onChange={(e) => setDomain(e.target.value)}
                  className="w-full px-4 py-2 border rounded-lg focus:ring-2 focus:ring-indigo-500"
                >
                  <option value="">Select domain</option>
                  {DOMAINS.map(d => (
                    <option key={d} value={d}>{d.charAt(0).toUpperCase() + d.slice(1)}</option>
                  ))}
                </select>
              </div>
            </div>

            {/* Tags */}
            <div>
              <label className="block text-sm font-medium text-gray-700 mb-2">
                Tags
              </label>
              <div className="flex flex-wrap gap-2 mb-2">
                {tags.map(tag => (
                  <span
                    key={tag}
                    className="inline-flex items-center gap-1 px-3 py-1 bg-indigo-100 text-indigo-700 rounded-full text-sm"
                  >
                    <Tag className="w-3 h-3" />
                    {tag}
                    <button onClick={() => handleRemoveTag(tag)} className="hover:text-indigo-900">
                      <X className="w-3 h-3" />
                    </button>
                  </span>
                ))}
              </div>
              <div className="flex gap-2">
                <input
                  type="text"
                  value={newTag}
                  onChange={(e) => setNewTag(e.target.value)}
                  onKeyPress={(e) => e.key === 'Enter' && handleAddTag()}
                  placeholder="Add a tag..."
                  className="flex-1 px-4 py-2 border rounded-lg focus:ring-2 focus:ring-indigo-500"
                />
                <button
                  onClick={handleAddTag}
                  className="px-4 py-2 bg-indigo-100 text-indigo-700 rounded-lg hover:bg-indigo-200"
                >
                  <Plus className="w-4 h-4" />
                </button>
              </div>
            </div>

            {/* Save Button */}
            <button
              onClick={saveOverview}
              className="w-full py-3 bg-indigo-600 text-white rounded-lg hover:bg-indigo-700 flex items-center justify-center gap-2"
            >
              <Save className="w-4 h-4" />
              Save Knowledge
            </button>
          </div>
        )}

        {/* Data Dictionary Tab */}
        {activeTab === 'dictionary' && (
          <div className="space-y-4">
            <p className="text-sm text-gray-600 mb-4">
              Define what each column means in business terms. This helps the AI give better answers.
            </p>
            
            {knowledge?.dataDictionary?.columns?.map((col) => (
              <div key={col.name} className="border rounded-lg p-4">
                <div className="flex items-center justify-between mb-2">
                  <div>
                    <span className="font-medium text-gray-900">{col.name}</span>
                    <span className="ml-2 text-xs text-gray-500 bg-gray-100 px-2 py-1 rounded">
                      {col.dataType}
                    </span>
                  </div>
                  {editingColumn === col.name ? (
                    <div className="flex gap-2">
                      <button
                        onClick={() => handleUpdateColumn(col.name)}
                        className="text-green-600 hover:text-green-700"
                      >
                        <Check className="w-4 h-4" />
                      </button>
                      <button
                        onClick={() => setEditingColumn(null)}
                        className="text-gray-400 hover:text-gray-600"
                      >
                        <X className="w-4 h-4" />
                      </button>
                    </div>
                  ) : (
                    <button
                      onClick={() => {
                        setEditingColumn(col.name);
                        setColumnDescription(col.description);
                        setColumnBusinessMeaning(col.businessMeaning || '');
                      }}
                      className="text-gray-400 hover:text-indigo-600"
                    >
                      <Edit2 className="w-4 h-4" />
                    </button>
                  )}
                </div>
                
                {editingColumn === col.name ? (
                  <div className="space-y-2 mt-2">
                    <input
                      type="text"
                      value={columnDescription}
                      onChange={(e) => setColumnDescription(e.target.value)}
                      placeholder="Technical description..."
                      className="w-full px-3 py-2 border rounded text-sm"
                    />
                    <input
                      type="text"
                      value={columnBusinessMeaning}
                      onChange={(e) => setColumnBusinessMeaning(e.target.value)}
                      placeholder="Business meaning (e.g., 'Total revenue from this customer')"
                      className="w-full px-3 py-2 border rounded text-sm"
                    />
                  </div>
                ) : (
                  <div className="text-sm text-gray-600">
                    <p>{col.description}</p>
                    {col.businessMeaning && (
                      <p className="text-indigo-600 mt-1">💡 {col.businessMeaning}</p>
                    )}
                    {col.examples?.length > 0 && (
                      <p className="text-gray-400 text-xs mt-1">
                        Examples: {col.examples.join(', ')}
                      </p>
                    )}
                  </div>
                )}
              </div>
            ))}
          </div>
        )}

        {/* Stories Tab */}
        {activeTab === 'stories' && (
          <div className="space-y-4">
            {/* Add Story Button */}
            {!showStoryForm && (
              <button
                onClick={() => setShowStoryForm(true)}
                className="w-full py-3 border-2 border-dashed border-gray-300 rounded-lg text-gray-600 hover:border-indigo-500 hover:text-indigo-600 flex items-center justify-center gap-2"
              >
                <Plus className="w-5 h-5" />
                Add Note or Story
              </button>
            )}

            {/* Story Form */}
            {showStoryForm && (
              <div className="bg-gray-50 rounded-lg p-4 space-y-4">
                <div className="flex gap-2 flex-wrap">
                  {STORY_CATEGORIES.map(cat => (
                    <button
                      key={cat.value}
                      onClick={() => setStoryCategory(cat.value as any)}
                      className={`px-3 py-1 rounded-full text-sm flex items-center gap-1 ${
                        storyCategory === cat.value
                          ? getCategoryColor(cat.value)
                          : 'bg-white border text-gray-600'
                      }`}
                    >
                      <cat.icon className="w-3 h-3" />
                      {cat.label}
                    </button>
                  ))}
                </div>
                <input
                  type="text"
                  value={storyTitle}
                  onChange={(e) => setStoryTitle(e.target.value)}
                  placeholder="Title..."
                  className="w-full px-4 py-2 border rounded-lg"
                />
                <textarea
                  value={storyContent}
                  onChange={(e) => setStoryContent(e.target.value)}
                  placeholder="Write your note, insight, or story..."
                  className="w-full px-4 py-3 border rounded-lg"
                  rows={4}
                />
                <div className="flex gap-2">
                  <button
                    onClick={handleAddStory}
                    className="px-4 py-2 bg-indigo-600 text-white rounded-lg hover:bg-indigo-700"
                  >
                    Add Story
                  </button>
                  <button
                    onClick={() => setShowStoryForm(false)}
                    className="px-4 py-2 text-gray-600 hover:text-gray-900"
                  >
                    Cancel
                  </button>
                </div>
              </div>
            )}

            {/* Stories List */}
            <div className="space-y-3">
              {knowledge?.stories?.slice().reverse().map(story => {
                const Icon = getCategoryIcon(story.category);
                return (
                  <div key={story.id} className="border rounded-lg p-4">
                    <div className="flex items-start gap-3">
                      <div className={`p-2 rounded-lg ${getCategoryColor(story.category)}`}>
                        <Icon className="w-4 h-4" />
                      </div>
                      <div className="flex-1">
                        <h4 className="font-medium text-gray-900">{story.title}</h4>
                        <p className="text-sm text-gray-600 mt-1">{story.content}</p>
                        <p className="text-xs text-gray-400 mt-2">
                          {new Date(story.createdAt).toLocaleDateString()}
                        </p>
                      </div>
                    </div>
                  </div>
                );
              })}
              
              {(!knowledge?.stories || knowledge.stories.length === 0) && !showStoryForm && (
                <div className="text-center py-8 text-gray-500">
                  <MessageSquare className="w-12 h-12 mx-auto mb-2 text-gray-300" />
                  <p>No stories yet. Add context about your data!</p>
                </div>
              )}
            </div>
          </div>
        )}

        {/* History Tab */}
        {activeTab === 'history' && (
          <div className="space-y-4">
            <p className="text-sm text-gray-600 mb-4">
              Recent questions and insights from AI conversations. The AI uses this for context.
            </p>
            
            {knowledge?.analysisHistory?.slice().reverse().map(insight => (
              <div key={insight.id} className="border rounded-lg p-4">
                <div className="flex items-start gap-2 mb-2">
                  <HelpCircle className="w-4 h-4 text-indigo-600 mt-1 flex-shrink-0" />
                  <p className="font-medium text-gray-900">{insight.question}</p>
                </div>
                <p className="text-sm text-gray-600 ml-6 line-clamp-3">{insight.answer}</p>
                <p className="text-xs text-gray-400 mt-2 ml-6">
                  {new Date(insight.timestamp).toLocaleString()}
                </p>
              </div>
            ))}
            
            {(!knowledge?.analysisHistory || knowledge.analysisHistory.length === 0) && (
              <div className="text-center py-8 text-gray-500">
                <Lightbulb className="w-12 h-12 mx-auto mb-2 text-gray-300" />
                <p>No analysis history yet. Start chatting with the AI!</p>
              </div>
            )}
          </div>
        )}
      </div>
    </div>
  );
};

export default DatasetKnowledgePanel;

