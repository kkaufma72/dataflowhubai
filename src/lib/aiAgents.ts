export interface AgentResponse {
  text: string;
  charts?: any[];
  insights?: string[];
  actions?: any[];
  metadata?: any;
}

/**
 * Check if dataset is from FRED
 */
const isFREDDataset = (dataset: Dataset): boolean => {
  return dataset.source === 'FRED' || 
         dataset.metadata?.source === 'FRED' ||
         dataset.tags?.includes('fred') ||
         dataset.tags?.includes('economic');
};

/**
 * Build FRED-specific context for AI
 */
const buildFREDContext = (dataset: Dataset): string => {
  const metadata = dataset.metadata || {};
  const series = metadata.series || {};
  
  let context = `\n\n## FRED Economic Dataset Context\n`;
  context += `This is official Federal Reserve Economic Data (FRED) from the St. Louis Federal Reserve.\n\n`;
  context += `**Series**: ${series.id || metadata.series_id || dataset.name}\n`;
  context += `**Title**: ${series.title || dataset.name}\n`;
  
  if (series.units || metadata.units) context += `**Units**: ${series.units || metadata.units}\n`;
  if (series.frequency || metadata.frequency) context += `**Frequency**: ${series.frequency || metadata.frequency}\n`;
  if (series.seasonal_adjustment) context += `**Seasonal Adjustment**: ${series.seasonal_adjustment}\n`;
  if (metadata.observation_start) context += `**Date Range**: ${metadata.observation_start} to ${metadata.observation_end || 'present'}\n`;
  
  context += `\n**Analysis Guidelines for Economic Data**:\n`;
  context += `- Reference historical economic events (recessions, policy changes) when relevant\n`;
  context += `- Consider seasonal patterns and year-over-year comparisons\n`;
  context += `- Note the data frequency and units when discussing values\n`;
  context += `- Relate to other key indicators (GDP, CPI, unemployment) when appropriate\n`;
  context += `- Be specific about time periods when discussing trends\n`;
  context += `- Explain economic terminology in accessible language\n`;
  
  // Add notes if available (truncated)
  if (series.notes) {
    context += `\n**Series Notes**: ${series.notes.substring(0, 800)}...\n`;
  }
  
  return context;
};

/**
 * Main orchestrator that coordinates all agents
 * 
 * SECURITY: All AI calls now go through secure Supabase Edge Function
 */
export const runAgentOrchestrator = async (
  question: string,
  dataset: Dataset,
  userProfile: UserProfile,
  conversationHistory: any[] = []
): Promise<AgentResponse> => {
  
  // Classify the intent
  const intent = await classifyIntent(question);

  // Route to appropriate agents
  const responses: any[] = [];

  // Build enhanced question with all available context
  let enhancedQuestion = question;
  let knowledgeContext = '';
  let semanticContext = '';
  
  try {
    // 1. Get structured knowledge base context for ALL datasets
    knowledgeContext = await buildKnowledgeContext(dataset);
    
    // 2. Semantic search for relevant knowledge chunks
    try {
      const relevantChunks = await searchKnowledge(question, {
        datasetId: dataset.id,
        matchThreshold: 0.7,
        matchCount: 5
      });
      
      if (relevantChunks.length > 0) {
        semanticContext = '\n\n## Relevant Knowledge (Semantic Search)\n';
        relevantChunks.forEach((chunk, idx) => {
          semanticContext += `${idx + 1}. [${chunk.chunkType}] ${chunk.chunkText}\n`;
        });
      }
    } catch (e) {
      console.warn('Semantic search failed, using structured context only:', e);
    }
    
    // 3. Add FRED-specific context if applicable
    if (isFREDDataset(dataset)) {
      const fredContext = buildFREDContext(dataset);
      knowledgeContext += fredContext;
      intent.isFREDData = true;
    }
    
    // 4. Auto-generate data dictionary if not exists (first time)
    if (!dataset.metadata?.dataDictionaryGenerated) {
      try {
        const autoDictionary = autoGenerateDataDictionary(dataset);
        await updateDatasetKnowledge(dataset.id, {
          datasetName: dataset.name,
          dataDictionary: autoDictionary
        });
        
        // Index the new knowledge for semantic search
        await indexDatasetKnowledge(dataset.id, {
          dataDictionary: autoDictionary
        });
      } catch (e) {
        console.warn('Could not auto-generate data dictionary:', e);
      }
    }
    
    enhancedQuestion = `${question}\n${knowledgeContext}${semanticContext}`;
  } catch (e) {
    console.warn('Could not build knowledge context:', e);
    // Continue with original question if knowledge base fails
  }

  // Call secure backend Edge Function instead of client-side OpenAI API
  try {
    const supabaseUrl = import.meta.env.VITE_SUPABASE_URL;
    const supabaseAnonKey = import.meta.env.VITE_SUPABASE_ANON_KEY;
    
    if (!supabaseUrl || !supabaseAnonKey) {
      throw new Error('Supabase configuration missing');
    }

    // Call secure Edge Function
    const response = await fetch(`${supabaseUrl}/functions/v1/ai-chat`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${supabaseAnonKey}`,
        'apikey': supabaseAnonKey
      },
      body: JSON.stringify({
        question: enhancedQuestion,
        dataset,
        userProfile,
        conversationHistory: conversationHistory.map(m => ({ role: m.role, content: m.content })),
        intent
      })
    });

    if (!response.ok) {
      const error = await response.json();
      throw new Error(error.error || 'Failed to get AI response');
    }

    const data = await response.json();
    const aiResponse = data.text || 'No response generated';
    
    responses.push({ 
      type: intent.needsMarketing ? "marketing" : "analysis", 
      content: aiResponse
    });
    
    // Save this Q&A to the knowledge base for future context
    try {
      await addAnalysisInsight(dataset.id, question, aiResponse);
    } catch (e) {
      console.warn('Could not save analysis insight:', e);
    }
  } catch (error: any) {
    console.error('AI agent error:', error);
    responses.push({
      type: "error",
      content: `I'm having trouble connecting right now. ${error.message || 'Please try again in a moment.'}`
    });
  }

  if (intent.needsChart) {
    try {
      // Chart generation temporarily disabled - requires refactoring
      responses.push({ 
        type: "chart", 
        content: "Chart generation is being enhanced. Use the visualization tab to create charts manually." 
      });
    } catch (error) {
      console.error('Chart generation error:', error);
      responses.push({ type: "chart", content: "Unable to generate chart at this time." });
    }
  }

  if (intent.needsInsights) {
    // Insight generation temporarily disabled - requires refactoring
    responses.push({ 
      type: "insight", 
      content: "Deep insights analysis is being enhanced. The AI response above includes key insights." 
    });
  }

  // If no responses, provide helpful fallback
  if (responses.length === 0) {
    responses.push({
      type: "fallback",
      content: `I can help you with:\n• Data analysis and statistics\n• Chart creation and visualization\n• Insight discovery and patterns${isMarketingUser(userProfile) ? '\n• Marketing strategy and campaigns\n• Customer personas and segmentation\n• Copywriting and content creation' : ''}\n\nWhat would you like to explore?`
    });
  }

  // Synthesize all responses
  return synthesizeAgentResponses(responses);
};

/**
 * Classify user intent
 */
const classifyIntent = async (question: string) => {
  const lowerQ = question.toLowerCase();
  
  return {
    needsAnalysis: true, // Always analyze
    needsChart: lowerQ.includes("show") || lowerQ.includes("chart") || lowerQ.includes("visualize") || lowerQ.includes("plot"),
    needsInsights: lowerQ.includes("insight") || lowerQ.includes("pattern") || lowerQ.includes("trend") || lowerQ.includes("why"),
    needsCleaning: lowerQ.includes("clean") || lowerQ.includes("fix") || lowerQ.includes("remove"),
    needsML: lowerQ.includes("predict") || lowerQ.includes("forecast") || lowerQ.includes("model"),
    needsMarketing: lowerQ.includes("campaign") || lowerQ.includes("email") || lowerQ.includes("copy") || 
                    lowerQ.includes("persona") || lowerQ.includes("segment") || lowerQ.includes("marketing") ||
                    lowerQ.includes("ad") || lowerQ.includes("social") || lowerQ.includes("content")
  };
};

/**
 * Synthesize responses from multiple agents
 */
const synthesizeAgentResponses = (responses: any[]): AgentResponse => {
  const text = responses
    .map(r => r.content)
    .join('\n\n');

  const charts = responses
    .filter(r => r.type === 'chart')
    .map(r => r.content);

  const insights = responses
    .filter(r => r.type === 'insight')
    .map(r => r.content);

  return {
    text,
    charts: charts.length > 0 ? charts : undefined,
    insights: insights.length > 0 ? insights : undefined
  };
};

export default runAgentOrchestrator;
